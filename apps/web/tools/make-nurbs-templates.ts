/**
 * The NURBS starter templates (docs/design/m2-editor.md §5): `.board` documents (version 3, the
 * section model) committed under `src/templates/`, so a template opens at once with no conversion.
 *
 * - the three classic templates (Shortboard, Funboard, Longboard) converted the way the app converts them
 *   when it opens the classic file with the engine on;
 * - a Swallow shortboard and a Fish shortboard: the shortboard with `setTail`.
 *
 * It also makes `src/board-type-shapes.ts`, what the New board gallery knows of each template without
 * loading it: the size it is drawn at and its plan outline, read from the rails board it opens as.
 *
 * This module is pure (it returns the texts); `make-nurbs-templates.test.ts` compares them with the
 * committed files, so a change to the converter or to `setTail` that would change a template (or the
 * gallery's data) fails the test instead of leaving the files stale. To write the files again:
 *
 *   NURBS_TEMPLATES_WRITE=1 pnpm --filter @openshaper/web exec vitest run tools/make-nurbs-templates.test.ts
 *
 * and commit the result. It runs under Vitest, not Node, because the workspace packages are consumed from
 * TypeScript source.
 */
import {
  boardDocToJson,
  convertSections,
  createChordFn,
  reviveBoardDoc,
  type BoardDoc,
  type Chain,
} from '@openshaper/board2';
import { convertClassic } from '@openshaper/board2/classic';
import { parseBrd } from '@openshaper/io';
import { createBoardStore } from '@openshaper/store';
import { setTail } from '@openshaper/store/sections';
import { measureRails } from '../src/board-sizing';
import funboardBrd from '../src/funboard.brd?raw';
import longboardBrd from '../src/longboard.brd?raw';
import shortboardBrd from '../src/sample-board.brd?raw';

export interface MadeTemplate {
  /** The name the New menu and the docs registry use. */
  readonly name: string;
  /** The file under `src/templates/`. */
  readonly file: string;
  readonly text: string;
}

const SOURCE = 'starter template';

/** A classic template, loaded into a classic store (which enforces the junctions) and converted. */
function converted(name: string, brd: string): BoardDoc {
  const store = createBoardStore();
  store.getState().load(parseBrd(brd).board);
  const r = convertClassic(store.getState().board!, { name, source: SOURCE });
  if (!r.ok) throw new Error(`${name}: ${r.issues.map((i) => i.message).join('; ')}`);
  return r.value.doc;
}

export function makeNurbsTemplates(): MadeTemplate[] {
  const shortboard = converted('Shortboard', shortboardBrd);
  type Made = { name: string; file: string; doc: BoardDoc };
  const named = (doc: BoardDoc, name: string): BoardDoc => ({
    ...doc,
    meta: { ...doc.meta, name },
  });
  const chords = (doc: BoardDoc, side?: 'minus') => createChordFn(doc, side);
  const docs: Made[] = [
    { name: 'Shortboard', file: 'shortboard.board', doc: shortboard },
    { name: 'Funboard', file: 'funboard.board', doc: converted('Funboard', funboardBrd) },
    { name: 'Longboard', file: 'longboard.board', doc: converted('Longboard', longboardBrd) },
    {
      name: 'Swallow shortboard',
      file: 'swallow-shortboard.board',
      doc: named(setTail(shortboard, 'swallow', undefined, chords), 'Swallow shortboard'),
    },
    {
      name: 'Fish shortboard',
      file: 'fish-shortboard.board',
      doc: named(setTail(shortboard, 'fish', undefined, chords), 'Fish shortboard'),
    },
  ];
  return docs.map(({ name, file, doc }) => ({ name, file, text: boardDocToJson(doc) }));
}

/** Where the generated board-type data is committed, beside `templates.ts`. */
export const SHAPES_FILE = 'board-type-shapes.ts';

/** A coordinate in cm to a millimetre, as short text (never "-0"). */
const mm = (n: number): string => String(Math.round(n * 10) / 10 + 0);

/** A board's size in cm to a micrometre: stable across machines, and finer than anything a shaper sets. */
const um = (n: number): number => Math.round(n * 1e4) / 1e4;

/**
 * An outline chain as an SVG path in the chain's own units, cm to a millimetre: one cubic segment from each
 * knot to the next, left open. Filled, it closes along the stringer; so a board's plan is this path and the
 * same path mirrored, drawn with no stroke along the stringer.
 */
export function planPath(chain: Chain): string {
  const k = chain.knots;
  const at = (p: readonly [number, number]) => `${mm(p[0])} ${mm(p[1])}`;
  let d = `M${at(k[0]!.p)}`;
  for (let i = 0; i + 1 < k.length; i++) {
    d += `C${at(k[i]!.out)} ${at(k[i + 1]!.in)} ${at(k[i + 1]!.p)}`;
  }
  return d;
}

const HEADER = `// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tools/make-nurbs-templates.ts from the templates in ./templates: do not edit. To write it
// again, run NURBS_TEMPLATES_WRITE=1 pnpm --filter @openshaper/web exec vitest run tools/make-nurbs-templates.test.ts
// and commit the result; the same test fails when this file is not what the generator makes.

/**
 * What each starter template is, read from the board it opens as (the rails board the engine makes of it), so
 * that the New board gallery can draw it and name its size without loading the template:
 * - \`length\`, \`width\` and \`thickness\` (cm, to a micrometre): the numbers the sidebar's specs show for the
 *   board, the thickness being the one at mid-length;
 * - \`plan\`: the outline of the board's plus half as an SVG path in cm (the tail at x = 0, the nose toward +x,
 *   y up from the stringer), to a millimetre. The half is drawn twice, the second mirrored.
 */
export interface BoardTypeShape {
  readonly length: number;
  readonly width: number;
  readonly thickness: number;
  readonly plan: string;
}

`;

const quoted = (name: string): string => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);

/** The text of `src/board-type-shapes.ts`: what the gallery knows of each template without loading it. */
export function makeBoardTypeShapes(): string {
  const entries = makeNurbsTemplates().map((t) => {
    const read = reviveBoardDoc(JSON.parse(t.text));
    if (!read.ok) throw new Error(`${t.name}: ${read.issues.map((i) => i.message).join('; ')}`);
    const made = convertSections(read.value);
    if (!made.ok) throw new Error(`${t.name}: ${made.issues.map((i) => i.message).join('; ')}`);
    const board = made.value.board;
    const size = measureRails(board);
    return `  ${quoted(t.name)}: {
    length: ${um(size.length)},
    width: ${um(size.width)},
    thickness: ${um(size.thickness)},
    plan: '${planPath(board.outline.plus)}',
  },`;
  });
  return `${HEADER}export const BOARD_TYPE_SHAPES: Readonly<Record<string, BoardTypeShape>> = {\n${entries.join('\n')}\n};\n`;
}
